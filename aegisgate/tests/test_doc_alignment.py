def test_placeholder_regex_copies_are_identical() -> None:
    """YAML, code defaults, and restoration.py fallback must stay byte-identical.

    A previous bug only changed the restoration.py fallback, which is unused
    whenever YAML loads, so the runtime regex stayed blind to kinds like IPV4.
    """
    yaml_rules = yaml.safe_load(_RULES.read_text(encoding="utf-8"))
    yaml_regex = yaml_rules["restoration"]["placeholder_regex"]
    default_regex = _DEFAULT_RULES["restoration"]["placeholder_regex"]

    restoration_src = (
        _REPO_ROOT / "aegisgate" / "filters" / "restoration.py"
    ).read_text(encoding="utf-8")
    fallback_match = re.search(
        r'get\(\s*"placeholder_regex"\s*,\s*r?"(.*)"\s*\)',
        restoration_src,
    )
    assert fallback_match, "restoration.py placeholder_regex fallback not found"
    fallback_regex = fallback_match.group(1)

    assert yaml_regex == default_regex == fallback_regex
    assert "[A-Z0-9_]+" in yaml_regex, (
        "kind segment must allow digits so IPV4/IPV6 placeholders are visible"
    )


@pytest.mark.parametrize("doc", _existing_docs(), ids=lambda p: p.name)
def test_relative_doc_links_resolve(doc: Path) -> None:
    """Relative Markdown links must point at files that exist."""
    text = doc.read_text(encoding="utf-8")
    broken: list[str] = []
    for target in re.findall(r"\]\(([^)\s]+)\)", text):
        if target.startswith(("http://", "https://", "mailto:", "#")):
            continue
        path_part = target.split("#", 1)[0]
        if not path_part:
            continue
        if not (doc.parent / path_part).exists():
            broken.append(target)
    assert not broken, f"{doc.name} has broken relative links: {broken}"


def _github_slug(heading: str) -> str:
    """Approximate GitHub's heading slugger.

    Punctuation is stripped, spaces become hyphens, and word characters —
    underscores included — are kept.
    """
    slug = heading.strip().lower()
    slug = re.sub(r"[^\w\s-]", "", slug, flags=re.UNICODE)
    return re.sub(r"\s", "-", slug)


@pytest.mark.parametrize("doc", _existing_docs(), ids=lambda p: p.name)
def test_in_page_anchors_resolve(doc: Path) -> None:
    """Same-document `#anchor` links must match a heading in that file."""
    text = doc.read_text(encoding="utf-8")
    headings = {
        _github_slug(m.group(1))
        for m in re.finditer(r"^#{1,6}\s+(.+?)\s*$", text, re.MULTILINE)
    }
    broken = [
        target
        for target in re.findall(r"\]\((#[^)\s]+)\)", text)
        if target[1:] not in headings
    ]
    assert not broken, (
        f"{doc.name} has in-page anchors matching no heading: {broken}. "
        f"Note GitHub keeps underscores in slugs."
    )


